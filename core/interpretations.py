# -----------------------------------------------------------------------------
# ۳) موتور تفسیر – تولید لیست قوانین فعال برای این چارت
# -----------------------------------------------------------------------------

def interpret_chart(chart: Dict[str, Any]) -> List[Dict[str, Any]]:
    """
    chart_data را می‌گیرد و لیستی از قوانین فعال (با متن، وزن، حوزه) برمی‌گرداند.
    """
    factors = extract_factors(chart)
    results: List[Dict[str, Any]] = []

    for f in factors:
        key = None

        if f["type"] == "planet_in_sign":
            key = ("planet_in_sign", f["planet"], f["sign"])

        elif f["type"] == "planet_in_house":
            key = ("planet_in_house", f["planet"], f["house"])

        elif f["type"] == "retrograde":
            key = ("retrograde", f["planet"])

        elif f["type"] == "aspect":
            key = ("aspect", f["p1"], f["p2"], f["aspect"])
            # تقارن: اگر پ۱–پ۲ نبود، پ۲–پ۱ را تست کن
            if key not in INTERP_RULES:
                key = ("aspect", f["p2"], f["p1"], f["aspect"])

        if key and key in INTERP_RULES:
            results.append(INTERP_RULES[key])

    # مرتب‌سازی بر اساس وزن
    results.sort(key=lambda r: r["weight"], reverse=True)
    return results


# -----------------------------------------------------------------------------
# ۴) فرمت نهایی برای کاربر (تلگرام)
# -----------------------------------------------------------------------------

def format_for_user(interpretations: List[Dict[str, Any]]) -> str:
    """
    لیست قوانین فعال را به یک متن چندبخشی و کاربرپسند تبدیل می‌کند.
    خروجی مناسب ارسال در تلگرام است.
    """
    sections: Dict[str, List[str]] = {}

    for rule in interpretations:
        dom = rule["domain"]
        sections.setdefault(dom, []).append(rule["text"])

    lines: List[str] = []

    # ترتیب حوزه‌ها مطابق اولویت تو
    domain_order = [
        "شخصیت و هویت",
        "روابط عاطفی",
        "شغل و مسیر زندگی",
        "چالش‌های درونی",
        "شانس و نقاط طلایی",
    ]

    for domain in domain_order:
        texts = sections.get(domain)
        if not texts:
            continue

        lines.append(f"🔹 {domain}")
        # حداکثر ۴ جملهٔ قوی‌تر برای هر بخش
        for t in texts[:4]:
            lines.append(f"• {t}")
        lines.append("")  # خط خالی بین بخش‌ها

    return "\n".join(lines).strip()
