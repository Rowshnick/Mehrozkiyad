from typing import Dict, Any, List

# -----------------------------------------------------------------------------
# ۱) استخراج فاکتورهای نجومی از chart_data
# -----------------------------------------------------------------------------

def extract_factors(chart: Dict[str, Any]) -> List[Dict[str, Any]]:
    """
    chart_data استاندارد را می‌گیرد و آن را به فهرست فاکتورهای تفسیری تبدیل می‌کند.
    انتظار ساختار مطابق خروجی calculate_natal_chart در astrology_core.py:
      - chart["planets_list"] : لیست سیارات با کلیدهای name, sign, house, retrograde, ...
      - chart["aspects"]      : لیست زوایا با p1, p2, aspect, orb
    """
    factors = []

    planets = chart.get("planets_list", [])
    aspects = chart.get("aspects", [])

    for p in planets:
        # سیاره در برج
        factors.append({
            "type": "planet_in_sign",
            "planet": p["name"],
            "sign": p["sign"],
        })

        # سیاره در خانه
        factors.append({
            "type": "planet_in_house",
            "planet": p["name"],
            "house": p["house"],
        })

        # رترگراد
        if p.get("retrograde", False):
            factors.append({
                "type": "retrograde",
                "planet": p["name"],
            })

    # زوایا
    for asp in aspects:
        factors.append({
            "type": "aspect",
            "p1": asp["p1"],
            "p2": asp["p2"],
            "aspect": asp["aspect"],
            "orb": asp["orb"],
        })

    return factors


