# =============================================================================
# تابع اصلی تفسیر
# =============================================================================

def interpret_natal_chart(chart_data: Dict[str, Any]) -> str:
    """
    ورودی: chart_data از astrology_core
    خروجی: متن تفسیر فارسی (MarkdownV2-safe)
    """

    if 'error' in chart_data:
        return utils.escape_markdown_v2(f"❌ خطا در محاسبه چارت: {chart_data['error']}")

    planets = chart_data['planets']          # دیکشنری
    aspects = chart_data['aspects']          # لیست
    houses = chart_data['houses']            # دیکشنری
    pof = chart_data['part_of_fortune']      # سهم سعادت

    # -------------------------------------------------------------------------
    # ۱) مقدمه
    # -------------------------------------------------------------------------
    text = "✨ *تفسیر چارت تولد شما* ✨\n\n"

    # -------------------------------------------------------------------------
    # ۲) تفسیر سیارات
    # -------------------------------------------------------------------------
    text += "🌞 *سیارات در برج‌ها و خانه‌ها*\n"

    for p_name, pdata in planets.items():
        if p_name not in PLANET_NAMES_FA:
            continue

        fa_name = PLANET_NAMES_FA[p_name]
        sign = pdata['sign']
        house = pdata['house']
        house_name = pdata['house_name']

        # تفسیر سیاره در برج
        sign_text = PLANET_IN_SIGN_FA.get(p_name, "").format(sign=sign)

        # تفسیر سیاره در خانه
        house_text = PLANET_IN_HOUSE_FA.get(house, "")

        text += (
            f"\n🔹 *{fa_name}* در برج *{sign}* "
            f"و {house_name}:\n"
            f"  - {sign_text}\n"
            f"  - {house_text}\n"
        )

    # -------------------------------------------------------------------------
    # ۳) تفسیر سهم سعادت
    # -------------------------------------------------------------------------
    text += "\n💠 *سهم سعادت (Part of Fortune)*\n"
    text += (
        f"سهم سعادت شما در برج *{pof['sign']}* "
        f"و {pof['house_name']} قرار دارد.\n"
        f"این نقطه نشان‌دهنده مسیر طبیعی خوش‌شانسی، هماهنگی و شکوفایی شماست.\n"
    )

    # -------------------------------------------------------------------------
    # ۴) تفسیر زوایا
    # -------------------------------------------------------------------------
    text += "\n🔭 *زوایا (Aspects) بین سیارات*\n"

    if not aspects:
        text += "هیچ زاویه مهمی بین سیارات یافت نشد.\n"
    else:
        for asp in aspects:
            p1 = PLANET_NAMES_FA.get(asp['p1'], asp['p1'])
            p2 = PLANET_NAMES_FA.get(asp['p2'], asp['p2'])
            asp_name = ASPECT_NAMES_FA.get(asp['aspect'], asp['aspect'])
            asp_text = ASPECT_INTERPRETATION_FA.get(asp['aspect'], "")
            orb = asp['orb']

            text += (
                f"\n⭐ *{p1}* و *{p2}* — {asp_name}\n"
                f"  - میزان اختلاف: {orb} درجه\n"
                f"  - {asp_text}\n"
            )

    # -------------------------------------------------------------------------
    # ۵) پایان‌بندی
    # -------------------------------------------------------------------------
    text += "\n✨ این تفسیر یک نگاه کلی به چارت شماست. برای تحلیل عمیق‌تر می‌توانیم بخش‌های بیشتری اضافه کنیم.\n"

    # Escape برای MarkdownV2
    return utils.escape_markdown_v2(text)
