# -----------------------------------------------------------------------------
# تطبیق ترانزیت با قوانین
# -----------------------------------------------------------------------------

def match_transit_rule(transit: Dict[str, Any]) -> TransitRule | None:
    """
    یک ترانزیت را گرفته و اگر قانون مربوطه وجود داشته باشد برمی‌گرداند.
    """
    t_planet = transit["transit_planet"].lower()
    n_point = transit["natal_point"].lower()
    aspect = transit["aspect"].lower()

    key = (t_planet, n_point, aspect)
    rule = TRANSIT_RULES.get(key)
    return rule


# -----------------------------------------------------------------------------
# فرمت خروجی – گروه‌بندی بر اساس تاریخ
# -----------------------------------------------------------------------------

def format_transits_for_user(transits_with_rules: List[Dict[str, Any]]) -> str:
    """
    ترانزیت‌های دارای قانون را بر اساس تاریخ گروه‌بندی و به متن تبدیل می‌کند.
    """

    by_date: Dict[date, List[Dict[str, Any]]] = {}
    for item in transits_with_rules:
        d = item["date"]
        by_date.setdefault(d, []).append(item)

    lines: List[str] = []

    for d in sorted(by_date.keys()):
        day_items = by_date[d]
        lines.append(f"📅 ترانزیت‌های مهم در تاریخ {d.isoformat()}:")
        lines.append("")

        # مرتب‌سازی در هر روز بر اساس وزن
        day_items_sorted = sorted(
            day_items,
            key=lambda x: x["rule"]["weight"],
            reverse=True
        )

        for it in day_items_sorted:
            tr = it["transit"]
            rule = it["rule"]

            tp = tr["transit_planet"].capitalize()
            np = tr["natal_point"].upper()
            asp = tr["aspect"]

            aspect_symbol = {
                "conjunction": "☌",
                "square": "□",
                "opposition": "☍",
                "trine": "△",
                "sextile": "✶",
            }.get(asp, asp)

            lines.append(f"🔶 {tp} {aspect_symbol} {np}")
            lines.append(f"• {rule['text']}")
            lines.append(f"  🔸 توصیهٔ عملی: {rule['advice']}")
            lines.append("")

        lines.append("")

    return "\n".join(lines).strip()


# -----------------------------------------------------------------------------
# API اصلی برای استفاده در bot_app و PDF
# -----------------------------------------------------------------------------

def analyze_transits_for_range(
    natal_chart: Dict[str, Any],
    start_date: date,
    end_date: date,
) -> str:
    """
    خروجی نهایی ترانزیت‌ها برای یک بازهٔ زمانی.
    - natal_chart: داده‌های چارت ناتال
    - start_date, end_date: بازهٔ تاریخ
    """

    if calculate_transits_for_range is None:
        # اگر هنوز در astro_engine پیاده‌سازی نشده باشد
        return ""

    # ۱) گرفتن ترانزیت‌ها از astro_engine
    # خروجی مورد انتظار: List[Dict[str, Any]] (طبق ساختار بالا)
    raw_transits: List[Dict[str, Any]] = calculate_transits_for_range(
        natal_chart,
        start_date,
        end_date,
    )

    # ۲) اتصال به قوانین
    transits_with_rules: List[Dict[str, Any]] = []
    for tr in raw_transits:
        rule = match_transit_rule(tr)
        if rule is None:
            continue
        transits_with_rules.append({
            "date": tr["date"],
            "transit": tr,
            "rule": rule,
        })

    # ۳) اگر ترانزیت مهم نداشتیم
    if not transits_with_rules:
        return ""

    # ۴) فرمت خروجی
    return format_transits_for_user(transits_with_rules)
