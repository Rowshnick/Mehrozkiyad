from typing import Dict, Any, List, TypedDict, Optional


# -----------------------------------------------------------------------------
# قالب قوانین Composite
# -----------------------------------------------------------------------------

class CompositeRule(TypedDict):
    text: str
    advice: str
    depth: str        # "پرو"
    weight: float
    domain: str       # شخصیت، عشق، شغل، چالش، کارما، شانس


# -----------------------------------------------------------------------------
# استخراج فاکتورهای لازم از chart_data
# -----------------------------------------------------------------------------

def extract_core_positions(chart: Dict[str, Any]) -> Dict[str, Any]:
    """
    از chart_data موقعیت‌های اصلی را استخراج می‌کند:
    - خورشید، ماه، زهره، مریخ، زحل، مشتری، پلوتو
    - ASC
    - خانه‌ها
    - زوایا
    """
    planets = chart.get("planets_list", [])
    aspects = chart.get("aspects", [])
    houses = chart.get("houses", {})

    out = {
        "sun": None,
        "moon": None,
        "venus": None,
        "mars": None,
        "saturn": None,
        "jupiter": None,
        "pluto": None,
        "asc": chart.get("ascendant_sign", None),
        "houses": houses,
        "aspects": aspects,
    }

    for p in planets:
        name = p["name"].lower()
        if name in out:
            out[name] = {
                "sign": p["sign"],
                "house": p["house"],
                "retro": p.get("retrograde", False),
            }

    return out


# -----------------------------------------------------------------------------
# استخراج ترکیب‌های مهم
# -----------------------------------------------------------------------------

def extract_composites(core: Dict[str, Any]) -> List[Dict[str, Any]]:
    """
    ترکیب‌های مهم را از موقعیت‌های اصلی استخراج می‌کند.
    خروجی: لیستی از dict شامل نوع ترکیب و جزئیات.
    """

    combos: List[Dict[str, Any]] = []

    # -----------------------------
    # ۱) خورشید + ماه
    # -----------------------------
    if core["sun"] and core["moon"]:
        combos.append({
            "type": "sun_moon",
            "sun_sign": core["sun"]["sign"],
            "moon_sign": core["moon"]["sign"],
        })

    # -----------------------------
    # ۲) خورشید + ASC
    # -----------------------------
    if core["sun"] and core["asc"]:
        combos.append({
            "type": "sun_asc",
            "sun_sign": core["sun"]["sign"],
            "asc_sign": core["asc"],
        })

    # -----------------------------
    # ۳) ماه + زهره
    # -----------------------------
    if core["moon"] and core["venus"]:
        combos.append({
            "type": "moon_venus",
            "moon_sign": core["moon"]["sign"],
            "venus_sign": core["venus"]["sign"],
        })

    # -----------------------------
    # ۴) زهره + مریخ
    # -----------------------------
    if core["venus"] and core["mars"]:
        combos.append({
            "type": "venus_mars",
            "venus_sign": core["venus"]["sign"],
            "mars_sign": core["mars"]["sign"],
        })

    # -----------------------------
    # ۵) زهره + زحل
    # -----------------------------
    if core["venus"] and core["saturn"]:
        combos.append({
            "type": "venus_saturn",
            "venus_sign": core["venus"]["sign"],
            "saturn_sign": core["saturn"]["sign"],
        })

    # -----------------------------
    # ۶) ماه + زحل
    # -----------------------------
    if core["moon"] and core["saturn"]:
        combos.append({
            "type": "moon_saturn",
            "moon_sign": core["moon"]["sign"],
            "saturn_sign": core["saturn"]["sign"],
        })

    # -----------------------------
    # ۷) خورشید + مشتری
    # -----------------------------
    if core["sun"] and core["jupiter"]:
        combos.append({
            "type": "sun_jupiter",
            "sun_sign": core["sun"]["sign"],
            "jupiter_sign": core["jupiter"]["sign"],
        })

    # -----------------------------
    # ۸) پلوتو + ماه (تحلیل عمیق روانی)
    # -----------------------------
    if core["moon"] and core["pluto"]:
        combos.append({
            "type": "moon_pluto",
            "moon_sign": core["moon"]["sign"],
            "pluto_sign": core["pluto"]["sign"],
        })

    # -----------------------------
    # ۹) گره شمالی + سیارات
    # -----------------------------
    nn = core.get("north_node")
    if nn:
        for planet in ["sun", "moon", "venus", "mars"]:
            if core.get(planet):
                combos.append({
                    "type": "northnode_planet",
                    "planet": planet,
                    "planet_sign": core[planet]["sign"],
                    "nn_sign": nn["sign"],
                })

    # -----------------------------
    # ۱۰) سیاره در خانه + سیاره در خانه (ترکیب خانه‌ها)
    # -----------------------------
    # مثال: خورشید خانه ۱۰ + زحل خانه ۶ → الگوی کاری خاص
    for p1 in ["sun", "moon", "venus", "mars", "saturn", "jupiter"]:
        for p2 in ["sun", "moon", "venus", "mars", "saturn", "jupiter"]:
            if p1 != p2 and core.get(p1) and core.get(p2):
                combos.append({
                    "type": "house_combo",
                    "p1": p1,
                    "p2": p2,
                    "h1": core[p1]["house"],
                    "h2": core[p2]["house"],
                })

    return combos


