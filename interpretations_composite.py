# ۴) فرمت خروجی Composite – برای تلگرام و PDF
# -----------------------------------------------------------------------------

def format_composite_for_user(rules: List[CompositeRule]) -> str:
    """
    قوانین Composite فعال را به متن چندبخشی تبدیل می‌کند.
    """

    sections: Dict[str, List[CompositeRule]] = {}

    for r in rules:
        dom = r["domain"]
        sections.setdefault(dom, []).append(r)

    lines: List[str] = []

    domain_order = [
        "شخصیت",
        "عشق",
        "شغل",
        "چالش",
        "کارما",
        "شانس",
    ]

    titles = {
        "شخصیت": "🔶 ترکیب‌های شخصیتی",
        "عشق": "💞 ترکیب‌های عاطفی",
        "شغل": "💼 ترکیب‌های شغلی",
        "چالش": "⚠️ ترکیب‌های چالشی",
        "کارما": "🜂 ترکیب‌های کارمایی",
        "شانس": "✨ ترکیب‌های شانس",
    }

    for domain in domain_order:
        rules_list = sections.get(domain)
        if not rules_list:
            continue

        lines.append(titles.get(domain, f"🔷 {domain}"))
        lines.append("")

        for r in rules_list:
            lines.append(f"• {r['text']}")
            lines.append(f"   🔸 توصیهٔ عملی: {r['advice']}")
            lines.append("")

        lines.append("")

    return "\n".join(lines).strip()


# -----------------------------------------------------------------------------
# ۵) خروجی نهایی برای اتصال به نسخهٔ PRO
# -----------------------------------------------------------------------------

def generate_composite_text(chart: Dict[str, Any]) -> str:
    """
    خروجی نهایی Composite برای استفاده در:
    - تلگرام
    - PDF
    - نسخهٔ PRO
    """
    rules = interpret_composite(chart)
    if not rules:
        return ""

    return format_composite_for_user(rules)
  
