# ۳) موتور Composite – فعال‌سازی قوانین ترکیبی
# -----------------------------------------------------------------------------

def interpret_composite(chart: Dict[str, Any]) -> List[CompositeRule]:
    """
    موتور اصلی Composite:
    - موقعیت‌های اصلی را استخراج می‌کند
    - ترکیب‌ها را می‌سازد
    - قوانین Composite را فعال می‌کند
    - خروجی را مرتب می‌کند
    """
    core = extract_core_positions(chart)
    combos = extract_composites(core)

    results: List[CompositeRule] = []

    for c in combos:
        t = c["type"]

        # -----------------------------
        # Sun + Moon
        # -----------------------------
        if t == "sun_moon":
            key = ("sun_moon", c["sun_sign"], c["moon_sign"])
            if key in COMPOSITE_RULES:
                results.append(COMPOSITE_RULES[key])

        # -----------------------------
        # Sun + ASC
        # -----------------------------
        elif t == "sun_asc":
            key = ("sun_asc", c["sun_sign"], c["asc_sign"])
            if key in COMPOSITE_RULES:
                results.append(COMPOSITE_RULES[key])

        # -----------------------------
        # Moon + Venus
        # -----------------------------
        elif t == "moon_venus":
            key = ("moon_venus", c["moon_sign"], c["venus_sign"])
            if key in COMPOSITE_RULES:
                results.append(COMPOSITE_RULES[key])

        # -----------------------------
        # Venus + Mars
        # -----------------------------
        elif t == "venus_mars":
            key = ("venus_mars", c["venus_sign"], c["mars_sign"])
            if key in COMPOSITE_RULES:
                results.append(COMPOSITE_RULES[key])

        # -----------------------------
        # Venus + Saturn
        # -----------------------------
        elif t == "venus_saturn":
            key = ("venus_saturn", c["venus_sign"], c["saturn_sign"])
            if key in COMPOSITE_RULES:
                results.append(COMPOSITE_RULES[key])

        # -----------------------------
        # Moon + Saturn
        # -----------------------------
        elif t == "moon_saturn":
            key = ("moon_saturn", c["moon_sign"], c["saturn_sign"])
            if key in COMPOSITE_RULES:
                results.append(COMPOSITE_RULES[key])

        # -----------------------------
        # Sun + Jupiter
        # -----------------------------
        elif t == "sun_jupiter":
            key = ("sun_jupiter", c["sun_sign"], c["jupiter_sign"])
            if key in COMPOSITE_RULES:
                results.append(COMPOSITE_RULES[key])

        # -----------------------------
        # Moon + Pluto
        # -----------------------------
        elif t == "moon_pluto":
            key = ("moon_pluto", c["moon_sign"], c["pluto_sign"])
            if key in COMPOSITE_RULES:
                results.append(COMPOSITE_RULES[key])

        # -----------------------------
        # House Combo
        # -----------------------------
        elif t == "house_combo":
            key = ("house_combo", c["p1"], c["p2"], c["h1"], c["h2"])
            if key in COMPOSITE_RULES:
                results.append(COMPOSITE_RULES[key])

        # -----------------------------
        # North Node + Planet
        # -----------------------------
        elif t == "northnode_planet":
            key = ("northnode_planet", c["planet"], c["planet_sign"], c["nn_sign"])
            if key in COMPOSITE_RULES:
                results.append(COMPOSITE_RULES[key])

    # مرتب‌سازی بر اساس وزن
    results.sort(key=lambda r: r["weight"], reverse=True)
    return results


