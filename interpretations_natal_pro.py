from typing import Dict, Any, List, TypedDict, Optional


class InterpretationRule(TypedDict):
    text: str
    focus: str           # "مثبت" | "چالش" | "خنثی"
    advice: str          # توصیهٔ عملی
    depth: str           # "سطحی" | "عمیق" | "پرو"
    weight: float
    domain: str          # شخصیت، عشق، شغل، چالش، شانس


# -----------------------------------------------------------------------------
# ۱) استخراج فاکتورهای نجومی از chart_data
# -----------------------------------------------------------------------------

def extract_factors(chart: Dict[str, Any]) -> List[Dict[str, Any]]:
    """
    chart_data استاندارد را می‌گیرد و آن را به فهرست فاکتورهای تفسیری تبدیل می‌کند.
    """
    factors: List[Dict[str, Any]] = []

    planets = chart.get("planets_list", [])
    aspects = chart.get("aspects", [])

    for p in planets:
        # سیاره در برج
        factors.append({
            "type": "planet_in_sign",
            "planet": p["name"].lower(),
            "sign": p["sign"],
        })

        # سیاره در خانه
        factors.append({
            "type": "planet_in_house",
            "planet": p["name"].lower(),
            "house": p["house"],
        })

        # رترگراد
        if p.get("retrograde", False):
            factors.append({
                "type": "retrograde",
                "planet": p["name"].lower(),
            })

    # زوایا
    for asp in aspects:
        factors.append({
            "type": "aspect",
            "p1": asp["p1"].lower(),
            "p2": asp["p2"].lower(),
            "aspect": asp["aspect"],
            "orb": asp["orb"],
        })

    return factors


