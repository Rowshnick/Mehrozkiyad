# ۴) ساخت متن کاربرپسند PRO – برای تلگرام و گزارش
# -----------------------------------------------------------------------------

def format_natal_pro_for_user(interpretations: List[InterpretationRule]) -> str:
    """
    لیست قوانین فعال PRO را می‌گیرد و به یک متن چندبخشی تبدیل می‌کند:
    - شخصیت و هویت
    - روابط عاطفی
    - شغل و مسیر زندگی
    - چالش‌های درونی
    - شانس و نقاط طلایی
    هر قانون با متن بلند + توصیهٔ عملی.
    """
    sections: Dict[str, List[InterpretationRule]] = {}

    for rule in interpretations:
        dom = rule["domain"]
        sections.setdefault(dom, []).append(rule)

    lines: List[str] = []

    domain_order = [
        "شخصیت و هویت",
        "روابط عاطفی",
        "شغل و مسیر زندگی",
        "چالش‌های درونی",
        "شانس و نقاط طلایی",
    ]

    titles = {
        "شخصیت و هویت": "🔷 شخصیت و هویت",
        "روابط عاطفی": "🔷 روابط عاطفی",
        "شغل و مسیر زندگی": "🔷 شغل و مسیر زندگی",
        "چالش‌های درونی": "🔷 چالش‌های درونی",
        "شانس و نقاط طلایی": "🔷 شانس‌ها و نقاط طلایی",
    }

    for domain in domain_order:
        rules = sections.get(domain)
        if not rules:
            continue

        lines.append(titles.get(domain, f"🔷 {domain}"))

        # تعداد قوانین پرو برای هر بخش – اگر خواستی می‌توانی بیشتر/کمتر کنی
        for r in rules[:5]:
            if r["focus"] == "مثبت":
                bullet = "✅"
            elif r["focus"] == "چالش":
                bullet = "⚠️"
            else:
                bullet = "•"

            lines.append(f"{bullet} {r['text']}")
            if r["advice"]:
                lines.append(f"   🔸 توصیهٔ عملی: {r['advice']}")
            lines.append("")

        lines.append("")

    return "\n".join(lines).strip()
