# ۳) موتور تفسیر PRO – تبدیل chart_data به لیست قوانین فعال
# -----------------------------------------------------------------------------

def interpret_natal_pro(chart: Dict[str, Any]) -> List[InterpretationRule]:
    """
    نسخهٔ حرفه‌ای تفسیر ناتال:
    - chart_data را می‌گیرد
    - فاکتورهای نجومی را استخراج می‌کند
    - قوانین PRO را فعال می‌کند
    - خروجی را بر اساس weight مرتب می‌کند
    """
    factors = extract_factors(chart)
    results: List[InterpretationRule] = []

    for f in factors:
        key: Optional[tuple] = None

        if f["type"] == "planet_in_sign":
            key = ("planet_in_sign", f["planet"], f["sign"])

        elif f["type"] == "planet_in_house":
            key = ("planet_in_house", f["planet"], f["house"])

        elif f["type"] == "retrograde":
            key = ("retrograde", f["planet"])

        elif f["type"] == "aspect":
            key = ("aspect", f["p1"], f["p2"], f["aspect"])
            if key not in INTERP_RULES_PRO:
                key = ("aspect", f["p2"], f["p1"], f["aspect"])

        if key and key in INTERP_RULES_PRO:
            results.append(INTERP_RULES_PRO[key])

    # مرتب‌سازی بر اساس وزن، و بعد بر اساس depth (پرو بالاتر)
    def sort_key(rule: InterpretationRule):
        depth_priority = {"سطحی": 0, "عمیق": 1, "پرو": 2}
        return (rule["weight"], depth_priority.get(rule["depth"], 1))

    results.sort(key=sort_key, reverse=True)
    return results
