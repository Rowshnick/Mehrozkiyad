def interpret_natal_chart(chart_data: Dict[str, Any]) -> str:
    interpretations = []
    
    # الف) طالع (Ascendant)
    asc_deg = chart_data.get('ascendant')
    if asc_deg is not None:
        sign_idx = int(asc_deg // 30)
        signs_en = list(SIGNS_MAP.keys())
        sign_fa = SIGNS_MAP[signs_en[sign_idx]]
        interpretations.append(f"🌅 **طالع (Rising Sign): {sign_fa}**\n{ASCENDANT_INTERPRETATIONS.get(sign_fa, '')}\n")

    # ب) سیارات
    planets = chart_data.get('planets', [])
    reverse_signs = {v: k for k, v in SIGNS_MAP.items()}
    
    interpretations.append("🪐 **تحلیل سیارات در بروج و خانه‌ها:**")
    for p in planets:
        p_name_en = p['name'].lower()
        p_fa = PLANETS_MAP.get(p_name_en.upper(), p_name_en)
        p_sign_fa = p['sign']
        p_house = p['house']
        retro = " ℞" if p.get('retrograde') else ""
        
        sign_key = reverse_signs.get(p_sign_fa, "ARIES")
        s_int = PLANET_IN_SIGN_INTERPRETATIONS.get(p_name_en, {}).get(sign_key, "")
        h_int = PLANET_IN_HOUSE_INTERPRETATIONS.get(p_house, {}).get(p_name_en, "")
        
        if s_int or h_int:
            interpretations.append(f"🔹 **{p_fa}{retro} در {p_sign_fa} (خانه {p_house}):**")
            if s_int: interpretations.append(f"   ▫️ {s_int}")
            if h_int: interpretations.append(f"   ▫️ {h_int}")
            interpretations.append("")

    # ج) زوایا (Aspects)
    aspects = chart_data.get('aspects', [])
    if aspects:
        interpretations.append("📐 **زوایای هندسی (Aspects):**")
        for asp in aspects:
            p1 = PLANETS_MAP.get(asp['p1'].upper(), asp['p1'])
            p2 = PLANETS_MAP.get(asp['p2'].upper(), asp['p2'])
            interpretations.append(f"  • {asp['type']} بین {p1} و {p2} (اُرب: {asp['orb']}°)")

    return "\n".join(interpretations)
